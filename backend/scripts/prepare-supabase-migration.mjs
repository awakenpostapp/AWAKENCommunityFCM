#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";

const input = process.argv[2];
const outputDir = process.argv[3];
if (!input || !outputDir) {
  console.error("Usage: node prepare-supabase-migration.mjs <d1-export.sql> <output-dir>");
  process.exit(2);
}

const sql = fs.readFileSync(input, "utf8");
fs.mkdirSync(outputDir, { recursive: true });

function splitStatements(source) {
  const result = [];
  let start = 0;
  let quoted = false;
  let quoteEscaped = false;
  for (let i = 0; i < source.length; i += 1) {
    const ch = source[i];
    if (quoted) {
      if (ch === "'" && source[i + 1] === "'") {
        i += 1;
        continue;
      }
      if (ch === "'" && !quoteEscaped) quoted = false;
      quoteEscaped = ch === "\\" && !quoteEscaped;
      if (ch !== "\\") quoteEscaped = false;
      continue;
    }
    if (ch === "'") {
      quoted = true;
      continue;
    }
    if (ch === ";") {
      const statement = source.slice(start, i + 1).trim();
      if (statement) result.push(statement);
      start = i + 1;
    }
  }
  const tail = source.slice(start).trim();
  if (tail) result.push(tail);
  return result;
}

function convertCreateTable(statement) {
  return statement
    .replace(/^CREATE TABLE IF NOT EXISTS /iu, "CREATE TABLE IF NOT EXISTS ")
    .replace(/INTEGER PRIMARY KEY AUTOINCREMENT/giu, "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    .replace(/\bREAL\b/gu, "DOUBLE PRECISION")
    .replace(/\s+COLLATE\s+NOCASE\b/giu, "")
    .replace(/\bTIMESTAMP\b/giu, "TIMESTAMPTZ")
    .replace(/\bCURRENT_TIMESTAMP\b/giu, "CURRENT_TIMESTAMP");
}

function convertIndex(statement) {
  return statement.replace(/^CREATE (UNIQUE )?INDEX /iu, (_m, unique) => `CREATE ${unique ?? ""}INDEX IF NOT EXISTS `);
}

const statements = splitStatements(sql);
const schema = [];
const data = [];
for (const statement of statements) {
  const normalized = statement.replace(/^\s*PRAGMA[^;]*;\s*$/iu, "").trim();
  if (!normalized) continue;
  if (/^CREATE TABLE/iu.test(normalized)) schema.push(convertCreateTable(normalized));
  else if (/^CREATE (UNIQUE )?INDEX/iu.test(normalized)) schema.push(convertIndex(normalized));
  else if (/^INSERT INTO/iu.test(normalized)) data.push(normalized);
}

const header = `-- Generated from Cloudflare D1 export.\n-- Source: ${path.basename(input)}\n-- Generated at: ${new Date().toISOString()}\n-- Do not use this file for Supabase Auth credentials; legacy password verifiers remain in public.users for the migration bridge.\n\n`;
fs.writeFileSync(path.join(outputDir, "schema.sql"), `${header}${schema.join("\n\n")}\n`, "utf8");

const batchSize = 25;
const batchFiles = [];
for (let i = 0; i < data.length; i += batchSize) {
  const batch = data.slice(i, i + batchSize);
  const name = `data-${String(batchFiles.length + 1).padStart(3, "0")}.sql`;
  fs.writeFileSync(path.join(outputDir, name), `${header}BEGIN;\n${batch.join("\n")}\nCOMMIT;\n`, "utf8");
  batchFiles.push(name);
}

const manifest = {
  source: path.basename(input),
  generatedAtUtc: new Date().toISOString(),
  tableDdlStatements: schema.filter((s) => /^CREATE TABLE/iu.test(s)).length,
  indexStatements: schema.filter((s) => /^CREATE (UNIQUE )?INDEX/iu.test(s)).length,
  dataStatements: data.length,
  dataBatchSize: batchSize,
  dataBatches: batchFiles,
};
fs.writeFileSync(path.join(outputDir, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
console.log(JSON.stringify(manifest, null, 2));
